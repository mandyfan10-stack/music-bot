#!/usr/bin/env node
// Переносит шрифты с Google Fonts в репозиторий: скачивает тот же CSS, что
// раньше подключался из index.html, кладёт woff2 в src/fonts/ и пишет
// src/fonts.css с локальными url(). unicode-range сохраняется, поэтому
// браузер по-прежнему грузит только нужные наборы символов.
//
// Шрифты (Inter, Playfair Display, Poiret One) — SIL Open Font License 1.1.
// Запуск (нужен интернет): npm run vendor:fonts
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const GOOGLE_CSS_URL = 'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700'
  + '&family=Playfair+Display:ital,wght@0,900;1,900&family=Poiret+One&display=swap';
// Google отдаёт woff2 только современным браузерам.
const USER_AGENT = 'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) '
  + 'Chrome/130.0 Mobile Safari/537.36';
const FONT_URL = /url\((https:\/\/fonts\.gstatic\.com\/s\/([a-z0-9]+)\/(v\d+)\/[^)]+\.woff2)\)/g;

// Имя файла: семейство-версия-хэш содержимого URL. Стабильно между запусками
// и меняется вместе с версией шрифта у Google, поэтому кэш сбрасывается сам.
function localName(url, family, version) {
  const hash = crypto.createHash('sha256').update(url).digest('hex').slice(0, 10);
  return `${family}-${version}-${hash}.woff2`;
}

function rewriteCss(css) {
  const files = [];
  const local = css.replace(FONT_URL, (_, url, family, version) => {
    const name = localName(url, family, version);
    files.push({ url, name });
    return `url(fonts/${name})`;
  });
  return { css: local, files };
}

async function main() {
  const res = await fetch(GOOGLE_CSS_URL, { headers: { 'User-Agent': USER_AGENT } });
  if (!res.ok) throw new Error(`Google Fonts CSS: HTTP ${res.status}`);
  const { css, files } = rewriteCss(await res.text());
  if (!files.length) throw new Error('No woff2 URLs in the Google Fonts CSS');

  const dir = path.join(root, 'src/fonts');
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  let total = 0;
  for (const { url, name } of files) {
    const font = await fetch(url);
    if (!font.ok) throw new Error(`${url}: HTTP ${font.status}`);
    const bytes = Buffer.from(await font.arrayBuffer());
    fs.writeFileSync(path.join(dir, name), bytes);
    total += bytes.length;
  }
  const header = '/* GENERATED by scripts/vendor-fonts.js from Google Fonts — do not edit.\n'
    + ' * Inter, Playfair Display, Poiret One: SIL Open Font License 1.1. */\n';
  fs.writeFileSync(path.join(root, 'src/fonts.css'), header + css);
  console.log(`Vendored ${files.length} font files (${Math.round(total / 1024)} KB) into src/fonts/`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.message || error);
    process.exit(1);
  });
}

module.exports = { rewriteCss, localName, GOOGLE_CSS_URL };
